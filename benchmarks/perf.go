// The performance benchmark times llm-semantic processes by wall clock. Its
// raw timings live in results-performance.json; results-performance.md is
// rendered from them and never edited by hand.
const (
	PerfJSONFile    = "results-performance.json"
	PerfResultsFile = "results-performance.md"
	// PerfMinFiles is the smallest input the large-input case may claim.
	PerfMinFiles = 3000
	// PerfDims is the vector size the fake embedder answers with.
	PerfDims = 256
	// PerfQuery is the search the typical-command case runs.
	PerfQuery = "load the config file and validate it"

	perfModel = "hash-256"
)

// Machine is what the table says the timings were taken on.
type Machine struct {
	CPU      string `json:"cpu"`
	Threads  int    `json:"threads"`
	RAMBytes uint64 `json:"ram_bytes"`
	OS       string `json:"os"`
	Kernel   string `json:"kernel"`
}

// PerfEmbedder describes the loopback fake the commands embed through.
type PerfEmbedder struct {
	LatencyMicros int64 `json:"latency_us"`
	Dims          int   `json:"dims"`
}

// PerfCorpus describes the large input: generated by the program, or the
// directory BENCH_DIR named. Files is what index reported it processed.
type PerfCorpus struct {
	Source string `json:"source"`
	Files  int    `json:"files"`
}

// PerfCase is one timed command. TimingsNS holds one wall-clock duration per
// timed run, in nanoseconds; warmup runs are not recorded.
type PerfCase struct {
	Name      string  `json:"name"`
	Command   string  `json:"command"`
	Warmup    int     `json:"warmup"`
	Runs      int     `json:"runs"`
	TimingsNS []int64 `json:"timings_ns"`
}

// PerfResults is the whole of results-performance.json.
type PerfResults struct {
	Version  string       `json:"version"`
	Date     string       `json:"date"`
	Machine  Machine      `json:"machine"`
	Embedder PerfEmbedder `json:"embedder"`
	Corpus   PerfCorpus   `json:"corpus"`
	Cases    []PerfCase   `json:"cases"`
}

// Validate refuses results that would print a number nobody measured: a
// case with no timings, a zero timing, fewer timings than runs, or a blank
// stamp.
func (r *PerfResults) Validate() error {
	var missing []string
	for name, blank := range map[string]bool{
		"version": r.Version == "", "date": r.Date == "",
		"machine cpu": r.Machine.CPU == "", "machine threads": r.Machine.Threads <= 0,
		"machine ram": r.Machine.RAMBytes == 0, "machine os": r.Machine.OS == "",
		"machine kernel": r.Machine.Kernel == "", "corpus files": r.Corpus.Files <= 0,
	} {
		if blank {
			missing = append(missing, name)
		}
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return fmt.Errorf("results lack %s", strings.Join(missing, ", "))
	}
	if len(r.Cases) == 0 {
		return errors.New("results hold no cases")
	}
	for _, c := range r.Cases {
		if len(c.TimingsNS) == 0 {
			return fmt.Errorf("case %q recorded zero timings; a case that measured nothing cannot be reported", c.Name)
		}
		if len(c.TimingsNS) != c.Runs {
			return fmt.Errorf("case %q has %d timings for %d runs", c.Name, len(c.TimingsNS), c.Runs)
		}
		for i, ns := range c.TimingsNS {
			if ns <= 0 {
				return fmt.Errorf("case %q run %d recorded %d ns", c.Name, i+1, ns)
			}
		}
	}
	return nil
}

// stats returns min, median, mean and max in milliseconds.
func stats(ns []int64) (lo, med, mean, hi float64) {
	s := append([]int64(nil), ns...)
	sort.Slice(s, func(i, j int) bool { return s[i] < s[j] })
	var sum float64
	for _, v := range s {
		sum += float64(v)
	}
	n := len(s)
	m := float64(s[n/2])
	if n%2 == 0 {
		m = (float64(s[n/2-1]) + float64(s[n/2])) / 2
	}
	return float64(s[0]) / 1e6, m / 1e6, sum / float64(n) / 1e6, float64(s[n-1]) / 1e6
}

// thousands formats n with comma separators.
func thousands(n int) string {
	s := strconv.Itoa(n)
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	return s
}

// RenderPerf formats results-performance.md from the results. Every figure
// in it comes from r.
func RenderPerf(r *PerfResults) (string, error) {
	if err := r.Validate(); err != nil {
		return "", err
	}
	var warm, runs []string
	for _, c := range r.Cases {
		warm = append(warm, fmt.Sprintf("%d (%s)", c.Warmup, c.Name))
		runs = append(runs, fmt.Sprintf("%d (%s)", c.Runs, c.Name))
	}
	source := "a corpus the program generates (Go, Python and Markdown files)"
	if r.Corpus.Source != "generated" {
		source = "the directory named by `BENCH_DIR`"
	}
	var b strings.Builder
	b.WriteString("# Performance\n\n")
	b.WriteString("<!-- Generated from results-performance.json by `make bench-perf`; do not edit. `make bench-perf-write` re-measures. -->\n\n")
	fmt.Fprintf(&b, "- **Version:** `%s` (`llm-semantic --version`)\n", r.Version)
	fmt.Fprintf(&b, "- **Date:** %s\n", r.Date)
	fmt.Fprintf(&b, "- **Machine:** %s, %d threads, %.1f GiB RAM, %s, kernel %s\n",
		r.Machine.CPU, r.Machine.Threads, float64(r.Machine.RAMBytes)/(1<<30), r.Machine.OS, r.Machine.Kernel)
	fmt.Fprintf(&b, "- **Method:** each case runs its warmup runs untimed, then its timed runs: warmup %s; runs %s. Each timing is the wall clock of one `llm-semantic` process, from start to exit, on the release build. Every `index` and `search` run also gets `--api-url`, `--model`, `--storage sqlite` and `--index-dir` pointing at the fake embedder and a temporary index; each `index` run starts from an empty index.\n",
		strings.Join(warm, ", "), strings.Join(runs, ", "))
	fmt.Fprintf(&b, "- **Embeddings:** a fixed-latency local fake: a loopback OpenAI-compatible server that waits %.1f ms per request and answers with deterministic %d-dimension hash vectors, so the numbers measure the tool and not a model.\n",
		float64(r.Embedder.LatencyMicros)/1000, r.Embedder.Dims)
	fmt.Fprintf(&b, "- **Large input:** %s files, %s.\n\n", thousands(r.Corpus.Files), source)
	b.WriteString("| Case | Command | Warmup | Runs | Min (ms) | Median (ms) | Mean (ms) | Max (ms) |\n")
	b.WriteString("|---|---|---:|---:|---:|---:|---:|---:|\n")
	for _, c := range r.Cases {
		lo, med, mean, hi := stats(c.TimingsNS)
		fmt.Fprintf(&b, "| %s | `%s` | %d | %d | %.1f | %.1f | %.1f | %.1f |\n",
			c.Name, strings.ReplaceAll(c.Command, "|", `\|`), c.Warmup, c.Runs, lo, med, mean, hi)
	}
	fmt.Fprintf(&b, "\nEvery timing is in [%s](%s). Measured by [`cmd/perf`](cmd/perf/main.go).\n", PerfJSONFile, PerfJSONFile)
	return b.String(), nil
}

// ReadPerf reads results-performance.json.
func ReadPerf(path string) (*PerfResults, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var r PerfResults
	if err := json.Unmarshal(data, &r); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return &r, nil
}

// WritePerfTable regenerates results-performance.md under dir from the JSON
// beside it. It writes nothing when the JSON fails validation.
func WritePerfTable(dir string, w io.Writer) error {
	r, err := ReadPerf(filepath.Join(dir, PerfJSONFile))
	if err != nil {
		return err
	}
	md, err := RenderPerf(r)
	if err != nil {
		return err
	}
	path := filepath.Join(dir, PerfResultsFile)
	if err := os.WriteFile(path, []byte(md), 0o644); err != nil {
		return err
	}
	_, _ = fmt.Fprintf(w, "%s\nwrote %s\n", md, path)
	return nil
}

// LatencyEmbedder waits Latency before handing each request to Next, so
// every embedding call costs the same fixed time.
type LatencyEmbedder struct {
	Latency time.Duration
	Next    http.Handler
}

func (l LatencyEmbedder) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	time.Sleep(l.Latency)
	l.Next.ServeHTTP(w, r)
}

// BuildCorpus writes n deterministic source files under dir, 100 to a
// package directory: two in three Go, the rest Python and Markdown.
func BuildCorpus(dir string, n int) error {
	for i := 0; i < n; i++ {
		pkg := fmt.Sprintf("pkg%03d", i/100)
		var name, body string
		switch i % 6 {
		case 4:
			name = fmt.Sprintf("module_%04d.py", i)
			body = fmt.Sprintf(pyTemplate, i, i, i, i, i, i)
		case 5:
			name = fmt.Sprintf("notes_%04d.md", i)
			body = fmt.Sprintf(mdTemplate, i, i, i, i)
		default:
			name = fmt.Sprintf("file_%04d.go", i)
			body = fmt.Sprintf(goTemplate, pkg, i, i, i, i, i, i, i, i, i, i, i)
		}
		p := filepath.Join(dir, pkg, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			return err
		}
	}
	return nil
}

const goTemplate = `package %s

import (
	"errors"
	"strings"
)

// Config%d holds the settings loaded for service %d.
type Config%d struct {
	Name    string
	Retries int
}

// LoadConfig%d parses a config file body into a Config%d.
func LoadConfig%d(body string) (*Config%d, error) {
	name := strings.TrimSpace(body)
	if name == "" {
		return nil, errors.New("empty config")
	}
	return &Config%d{Name: name, Retries: 3}, ValidateConfig%d(name)
}

// ValidateConfig%d rejects names with spaces in them.
func ValidateConfig%d(name string) error {
	if strings.Contains(name, " ") {
		return errors.New("name has a space")
	}
	return nil
}
`

const pyTemplate = `"""Request handling for worker %d."""


class Handler%d:
    """Retries a request until it succeeds."""

    def __init__(self, retries=3):
        self.retries = retries

    def handle(self, request):
        for attempt in range(self.retries):
            if request.send():
                return attempt
        raise RuntimeError("request %d failed")


def parse_header_%d(line):
    key, _, value = line.partition(":")
    return key.strip().lower(), value.strip()


def worker_%d():
    return Handler%d()
`

const mdTemplate = `# Notes %d

## Deploying service %d

Build the binary, copy it to the host and restart the unit. Check the log
for the line that says the config file was loaded.

## Rolling back

Keep the previous release next to the new one. Point the link back at it
and restart. Release %d replaced release %d.
`

// CountFiles counts the regular files under dir, skipping the directories
// llm-semantic's index skips by default.
func CountFiles(dir string) (int, error) {
	n := 0
	err := filepath.WalkDir(dir, func(_ string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			switch d.Name() {
			case ".git", "vendor", "node_modules":
				return filepath.SkipDir
			}
			return nil
		}
		if d.Type().IsRegular() {
			n++
		}
		return nil
	})
	return n, err
}

// ReadMachine reads the CPU, thread count, RAM, OS and kernel of this
// machine. It fails rather than stamp a blank field.
func ReadMachine() (Machine, error) {
	m := Machine{Threads: runtime.NumCPU()}
	platform := runtime.GOOS + "/" + runtime.GOARCH
	switch runtime.GOOS {
	case "linux":
		cpuinfo, _ := os.ReadFile("/proc/cpuinfo")
		m.CPU = procField(string(cpuinfo), "model name", "Model", "Hardware")
		meminfo, _ := os.ReadFile("/proc/meminfo")
		if kb, err := strconv.ParseUint(strings.Fields(procField(string(meminfo), "MemTotal") + " 0")[0], 10, 64); err == nil {
			m.RAMBytes = kb * 1024
		}
		release, _ := os.ReadFile("/etc/os-release")
		if name := strings.Trim(procFieldSep(string(release), "PRETTY_NAME", "="), `"`); name != "" {
			m.OS = name + " (" + platform + ")"
		}
		kernel, _ := os.ReadFile("/proc/sys/kernel/osrelease")
		m.Kernel = strings.TrimSpace(string(kernel))
	case "darwin":
		m.CPU = sysctl("machdep.cpu.brand_string")
		m.RAMBytes, _ = strconv.ParseUint(sysctl("hw.memsize"), 10, 64)
		if v := commandOutput("sw_vers", "-productVersion"); v != "" {
			m.OS = "macOS " + v + " (" + platform + ")"
		}
		m.Kernel = sysctl("kern.osrelease")
	}
	if m.CPU == "" || m.RAMBytes == 0 || m.OS == "" || m.Kernel == "" {
		return m, fmt.Errorf("could not read every machine fact on %s: %+v", platform, m)
	}
	return m, nil
}

// procField returns the value of the first key present in a "key : value"
// listing such as /proc/cpuinfo.
func procField(text string, keys ...string) string {
	for _, k := range keys {
		if v := procFieldSep(text, k, ":"); v != "" {
			return v
		}
	}
	return ""
}

func procFieldSep(text, key, sep string) string {
	for _, line := range strings.Split(text, "\n") {
		k, v, ok := strings.Cut(line, sep)
		if ok && strings.TrimSpace(k) == key {
			return strings.TrimSpace(v)
		}
	}
	return ""
}

func sysctl(name string) string { return commandOutput("sysctl", "-n", name) }

func commandOutput(name string, args ...string) string {
	out, err := exec.Command(name, args...).Output()
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(out))
}

// PerfConfig drives MeasurePerf.
type PerfConfig struct {
	CLI         string        // llm-semantic binary
	OutDir      string        // where the JSON and the table are written
	Corpus      string        // BENCH_DIR; empty generates Files files
	Files       int           // files to generate when Corpus is empty
	MinFiles    int           // fewest files the large input may hold
	Warmup      int           // untimed runs before the cold-start and typical cases
	Runs        int           // timed runs of the cold-start and typical cases
	IndexWarmup int           // untimed runs before the large-input case
	IndexRuns   int           // timed runs of the large-input case
	Latency     time.Duration // the fake embedder's wait per request
	Now         func() time.Time
	Machine     func() (Machine, error)
	Log         func(string)
}

// childEnv is the environment the CLI runs in: this one, less anything that
// would point it at another embedder, index or Qdrant.
func childEnv() []string {
	var env []string
	for _, kv := range os.Environ() {
		if strings.HasPrefix(kv, "LLM_SEMANTIC_") || strings.HasPrefix(kv, "QDRANT_") {
			continue
		}
		env = append(env, kv)
	}
	return env
}

// timeRun runs the CLI once and returns its wall clock and stdout. A
// non-zero exit is an error, never a timing.
func timeRun(ctx context.Context, cli, dir string, args []string) (time.Duration, []byte, error) {
	cmd := exec.CommandContext(ctx, cli, args...)
	cmd.Dir = dir
	cmd.Env = childEnv()
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	start := time.Now()
	err := cmd.Run()
	d := time.Since(start)
	if err != nil {
		return 0, nil, fmt.Errorf("%s %s: %w: %s", filepath.Base(cli), strings.Join(args, " "), err, strings.TrimSpace(stderr.String()))
	}
	return d, stdout.Bytes(), nil
}

// timeCase runs a case warmup+runs times, checking every run's output with
// check, and records the timed runs.
func timeCase(ctx context.Context, cfg PerfConfig, c *PerfCase, dir string, args []string, before func() error, check func([]byte) error) error {
	cfg.Log(fmt.Sprintf("%s: %d warmup, %d runs", c.Name, c.Warmup, c.Runs))
	for i := 0; i < c.Warmup+c.Runs; i++ {
		if before != nil {
			if err := before(); err != nil {
				return err
			}
		}
		d, out, err := timeRun(ctx, cfg.CLI, dir, args)
		if err != nil {
			return fmt.Errorf("case %q: %w", c.Name, err)
		}
		if err := check(out); err != nil {
			return fmt.Errorf("case %q run %d: %w", c.Name, i+1, err)
		}
		if i >= c.Warmup {
			c.TimingsNS = append(c.TimingsNS, d.Nanoseconds())
		}
	}
	if len(c.TimingsNS) == 0 {
		return fmt.Errorf("case %q recorded zero timings; a case that measured nothing cannot be reported", c.Name)
	}
	return nil
}

// MeasurePerf times the three cases against a loopback fake embedder and
// returns the results. It returns an error for any run that failed or did
// not do its job.
func MeasurePerf(ctx context.Context, cfg PerfConfig) (*PerfResults, error) {
	machine, err := cfg.Machine()
	if err != nil {
		return nil, err
	}
	// The commands run in a scratch directory, so a relative path would
	// name a binary that is not there.
	if cfg.CLI, err = filepath.Abs(cfg.CLI); err != nil {
		return nil, err
	}
	tmp, err := os.MkdirTemp("", "llm-semantic-perf-")
	if err != nil {
		return nil, err
	}
	defer func() { _ = os.RemoveAll(tmp) }()

	r := &PerfResults{
		Date:     cfg.Now().UTC().Format("2006-01-02"),
		Machine:  machine,
		Embedder: PerfEmbedder{LatencyMicros: cfg.Latency.Microseconds(), Dims: PerfDims},
	}
	corpus, want := cfg.Corpus, 0
	if corpus == "" {
		corpus = filepath.Join(tmp, "corpus")
		cfg.Log(fmt.Sprintf("generating %d files", cfg.Files))
		if err := BuildCorpus(corpus, cfg.Files); err != nil {
			return nil, err
		}
		r.Corpus.Source, want = "generated", cfg.Files
	} else {
		if corpus, err = filepath.Abs(corpus); err != nil {
			return nil, err
		}
		r.Corpus.Source = "BENCH_DIR"
	}
	if n, err := CountFiles(corpus); err != nil {
		return nil, err
	} else if n < cfg.MinFiles {
		return nil, fmt.Errorf("%s holds %d files; the large input needs at least %d", corpus, n, cfg.MinFiles)
	}

	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		return nil, err
	}
	srv := &http.Server{Handler: LatencyEmbedder{Latency: cfg.Latency, Next: HashEmbedder{Dims: PerfDims}}}
	go func() { _ = srv.Serve(ln) }()
	defer func() { _ = srv.Close() }()

	work := filepath.Join(tmp, "work")
	indexDir := filepath.Join(tmp, "index")
	if err := os.MkdirAll(work, 0o755); err != nil {
		return nil, err
	}
	plumbing := []string{"--api-url", "http://" + ln.Addr().String(), "--model", perfModel, "--storage", "sqlite", "--index-dir", indexDir}

	cold := PerfCase{Name: "cold start", Command: "llm-semantic --version", Warmup: cfg.Warmup, Runs: cfg.Runs}
	if err := timeCase(ctx, cfg, &cold, work, []string{"--version"}, nil, func(out []byte) error {
		r.Version = strings.TrimSpace(string(out))
		if r.Version == "" {
			return errors.New("--version printed nothing")
		}
		return nil
	}); err != nil {
		return nil, err
	}

	large := PerfCase{Name: "large input", Command: "llm-semantic index <corpus> --json", Warmup: cfg.IndexWarmup, Runs: cfg.IndexRuns}
	if err := timeCase(ctx, cfg, &large, work, append([]string{"index", corpus, "--json"}, plumbing...),
		func() error { return os.RemoveAll(indexDir) },
		func(out []byte) error {
			var res struct {
				FilesProcessed int      `json:"files_processed"`
				FilesSkipped   int      `json:"files_skipped"`
				ChunksCreated  int      `json:"chunks_created"`
				Errors         []string `json:"errors"`
			}
			if err := json.Unmarshal(out, &res); err != nil {
				return fmt.Errorf("index output is not JSON: %w", err)
			}
			switch {
			case len(res.Errors) > 0 || res.FilesSkipped > 0:
				return fmt.Errorf("index skipped %d files with errors: %v", res.FilesSkipped, res.Errors)
			case res.ChunksCreated == 0:
				return errors.New("index created no chunks")
			case want > 0 && res.FilesProcessed != want:
				return fmt.Errorf("index processed %d files; the corpus holds %d", res.FilesProcessed, want)
			case res.FilesProcessed < cfg.MinFiles:
				return fmt.Errorf("index processed %d files; the large input needs at least %d", res.FilesProcessed, cfg.MinFiles)
			case r.Corpus.Files != 0 && res.FilesProcessed != r.Corpus.Files:
				return fmt.Errorf("index processed %d files, an earlier run %d", res.FilesProcessed, r.Corpus.Files)
			}
			r.Corpus.Files = res.FilesProcessed
			return nil
		}); err != nil {
		return nil, err
	}
	typical := PerfCase{Name: "typical command", Command: fmt.Sprintf("llm-semantic search %q --json", PerfQuery), Warmup: cfg.Warmup, Runs: cfg.Runs}
	if err := timeCase(ctx, cfg, &typical, work, append([]string{"search", PerfQuery, "--json"}, plumbing...), nil, func(out []byte) error {
		var results []json.RawMessage
		if err := json.Unmarshal(out, &results); err != nil {
			return fmt.Errorf("search output is not a result array: %w", err)
		}
		if len(results) == 0 {
			return errors.New("search found nothing; an empty search is not a benchmark")
		}
		return nil
	}); err != nil {
		return nil, err
	}

	r.Cases = []PerfCase{cold, typical, large}
	return r, r.Validate()
}

// RunPerf measures, then writes results-performance.json and the table
// rendered from it. A failed or empty measurement writes neither file.
func RunPerf(ctx context.Context, cfg PerfConfig, w io.Writer) error {
	r, err := MeasurePerf(ctx, cfg)
	if err != nil {
		return err
	}
	md, err := RenderPerf(r)
	if err != nil {
		return err
	}
	data, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(cfg.OutDir, PerfJSONFile), append(data, '\n'), 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(cfg.OutDir, PerfResultsFile), []byte(md), 0o644); err != nil {
		return err
	}
	_, _ = fmt.Fprintf(w, "%s\nwrote %s and %s\n", md, PerfJSONFile, PerfResultsFile)
	return nil
}
