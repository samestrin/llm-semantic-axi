// Package benchmarks measures what llm-semantic's output costs a model to
// read. The search outputs it counts are checked in under outputs/, and the
// tokenizer's ranks file is vendored next to them, so a re-count needs no
// network and no embedding endpoint. results-tokens.md states the method.
package benchmarks

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/pkoukk/tiktoken-go"
)

const (
	// RanksFile is OpenAI's cl100k_base.tiktoken, vendored unchanged.
	RanksFile = "cl100k_base.tiktoken"
	// RanksSHA256 is the hash tiktoken itself checks the file against.
	RanksSHA256 = "223921b76ee99bde995b7ff738513eef100fb51d18c93597a113bcffe865b2a7"

	QueriesFile = "queries.txt"
	OutputsDir  = "outputs"
	ResultsFile = "results-tokens.md"

	BlockBegin = "<!-- tokens:begin (generated by `make bench-tokens-write`; do not edit) -->"
	BlockEnd   = "<!-- tokens:end -->"
)

// cl100kPattern is the pre-tokenizer split from tiktoken's cl100k_base.
const cl100kPattern = `(?i:'s|'t|'re|'ve|'m|'ll|'d)|[^\r\n\p{L}\p{N}]?\p{L}+|\p{N}{1,3}| ?[^\s\p{L}\p{N}]+[\r\n]*|\s*[\r\n]+|\s+(?!\S)|\s+`

var cl100kSpecial = map[string]int{
	"<|endoftext|>":   100257,
	"<|fim_prefix|>":  100258,
	"<|fim_middle|>":  100259,
	"<|fim_suffix|>":  100260,
	"<|endofprompt|>": 100276,
}

// Format is one output mode of the CLI.
type Format struct {
	Dir   string   // directory under outputs/
	Ext   string   // file extension of each output
	Name  string   // name in the results table
	Flag  string   // flag as shown in the results table
	Says  string   // how a sentence names this mode
	Flags []string // flags passed to the CLI
}

// Formats lists the measured modes. JSON comes first: it is the baseline the
// others are compared to, and the generator checks its result count.
var Formats = []Format{
	{Dir: "json", Ext: "json", Name: "JSON", Flag: "`--json`", Says: "`--json`", Flags: []string{"--json"}},
	{Dir: "axi", Ext: "toon", Name: "TOON", Flag: "`--axi`", Says: "`--axi`", Flags: []string{"--axi"}},
	{Dir: "plain", Ext: "txt", Name: "Plain", Flag: "*(none)*", Says: "plain output", Flags: nil},
}

// OutputPath is where query i's output in format f lives under dir.
func OutputPath(dir string, f Format, i int) string {
	return filepath.Join(dir, OutputsDir, f.Dir, fmt.Sprintf("q%02d.%s", i+1, f.Ext))
}

// Tokenizer counts cl100k_base tokens.
type Tokenizer struct {
	tk *tiktoken.Tiktoken
}

// LoadCL100K builds the tokenizer from a local ranks file. It refuses a file
// whose hash is not cl100k_base's, and it never touches the network.
func LoadCL100K(path string) (*Tokenizer, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read ranks: %w", err)
	}
	sum := sha256.Sum256(data)
	if got := hex.EncodeToString(sum[:]); got != RanksSHA256 {
		return nil, fmt.Errorf("ranks file %s: sha256 %s, want %s (not cl100k_base)", path, got, RanksSHA256)
	}
	ranks := make(map[string]int, 100256)
	for n, line := range bytes.Split(data, []byte("\n")) {
		if len(line) == 0 {
			continue
		}
		tok, rank, ok := bytes.Cut(line, []byte(" "))
		if !ok {
			return nil, fmt.Errorf("ranks file %s line %d: no rank", path, n+1)
		}
		b, err := base64.StdEncoding.DecodeString(string(tok))
		if err != nil {
			return nil, fmt.Errorf("ranks file %s line %d: %w", path, n+1, err)
		}
		r, err := strconv.Atoi(string(rank))
		if err != nil {
			return nil, fmt.Errorf("ranks file %s line %d: %w", path, n+1, err)
		}
		ranks[string(b)] = r
	}
	bpe, err := tiktoken.NewCoreBPE(ranks, cl100kSpecial, cl100kPattern)
	if err != nil {
		return nil, err
	}
	enc := &tiktoken.Encoding{Name: "cl100k_base", PatStr: cl100kPattern, MergeableRanks: ranks, SpecialTokens: cl100kSpecial}
	set := map[string]any{}
	for k := range cl100kSpecial {
		set[k] = true
	}
	return &Tokenizer{tk: tiktoken.NewTiktoken(bpe, enc, set)}, nil
}

// Encode returns the token IDs of text. Special-token text is ordinary text.
func (t *Tokenizer) Encode(text string) []int { return t.tk.EncodeOrdinary(text) }

// Count returns the number of tokens in text.
func (t *Tokenizer) Count(text string) int { return len(t.Encode(text)) }

// Measure is the size of one output.
type Measure struct {
	Tokens int
	Bytes  int
}

// Result holds the counts for every query in every format.
type Result struct {
	Queries []string
	Counts  map[string][]Measure // by Format.Dir, indexed like Queries
}

// Total sums one format over every query.
func (r *Result) Total(f Format) Measure {
	var m Measure
	for _, c := range r.Counts[f.Dir] {
		m.Tokens += c.Tokens
		m.Bytes += c.Bytes
	}
	return m
}

// ReadQueries reads the query list: one query per line, blank lines and
// lines starting with # skipped.
func ReadQueries(path string) ([]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var qs []string
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		qs = append(qs, line)
	}
	return qs, sc.Err()
}

// Count re-counts the checked-in outputs under dir. Every query must have a
// non-empty output in every format, and no format may hold an output for a
// query that is not in the list, so each total covers the same searches.
func Count(tok *Tokenizer, dir string) (*Result, error) {
	qs, err := ReadQueries(filepath.Join(dir, QueriesFile))
	if err != nil {
		return nil, err
	}
	if len(qs) == 0 {
		return nil, fmt.Errorf("%s lists no queries", filepath.Join(dir, QueriesFile))
	}
	res := &Result{Queries: qs, Counts: map[string][]Measure{}}
	for _, f := range Formats {
		entries, err := os.ReadDir(filepath.Join(dir, OutputsDir, f.Dir))
		if err != nil {
			return nil, err
		}
		want := map[string]bool{}
		for i := range qs {
			want[filepath.Base(OutputPath(dir, f, i))] = true
		}
		var stray []string
		for _, e := range entries {
			if !want[e.Name()] {
				stray = append(stray, e.Name())
			}
		}
		if len(stray) > 0 {
			sort.Strings(stray)
			return nil, fmt.Errorf("%s: outputs for no listed query: %s", f.Dir, strings.Join(stray, ", "))
		}
		for i := range qs {
			p := OutputPath(dir, f, i)
			data, err := os.ReadFile(p)
			if err != nil {
				return nil, err
			}
			if len(bytes.TrimSpace(data)) == 0 {
				return nil, fmt.Errorf("%s is empty: an empty output is a failed render, not a cheap one", p)
			}
			res.Counts[f.Dir] = append(res.Counts[f.Dir], Measure{Tokens: tok.Count(string(data)), Bytes: len(data)})
		}
	}
	return res, nil
}

// Render formats the results as the markdown that sits between the markers
// in results-tokens.md.
func Render(r *Result) string {
	var b strings.Builder
	base := r.Total(Formats[0]).Tokens
	n := float64(len(r.Queries))
	fmt.Fprintf(&b, "Totals over %d queries:\n\n", len(r.Queries))
	b.WriteString("| Format | Flag | Tokens (cl100k) | Bytes | Tokens per query | vs `--json` |\n")
	b.WriteString("|---|---|---:|---:|---:|---:|\n")
	for _, f := range Formats {
		t := r.Total(f)
		fmt.Fprintf(&b, "| %s | %s | %d | %d | %.1f | %s |\n",
			f.Name, f.Flag, t.Tokens, t.Bytes, float64(t.Tokens)/n, pct(t.Tokens, base))
	}
	fmt.Fprintf(&b, "\nOn these %d queries, %s printed %s of the tokens %s printed, and %s printed %s.\n",
		len(r.Queries), Formats[1].Says, pct(r.Total(Formats[1]).Tokens, base), Formats[0].Says,
		Formats[2].Says, pct(r.Total(Formats[2]).Tokens, base))
	b.WriteString("\nTokens per query:\n\n| # | Query |")
	for _, f := range Formats {
		fmt.Fprintf(&b, " %s |", f.Flag)
	}
	b.WriteString("\n|---:|---|")
	for range Formats {
		b.WriteString("---:|")
	}
	b.WriteString("\n")
	for i, q := range r.Queries {
		fmt.Fprintf(&b, "| %d | %s |", i+1, strings.ReplaceAll(q, "|", `\|`))
		for _, f := range Formats {
			fmt.Fprintf(&b, " %d |", r.Counts[f.Dir][i].Tokens)
		}
		b.WriteString("\n")
	}
	return b.String()
}

func pct(n, base int) string {
	return fmt.Sprintf("%.1f%%", 100*float64(n)/float64(base))
}

func splitBlock(data string) (before, block, after string, err error) {
	i := strings.Index(data, BlockBegin+"\n")
	j := strings.Index(data, BlockEnd)
	if i < 0 || j < i {
		return "", "", "", errors.New("no generated block: markers missing or out of order")
	}
	start := i + len(BlockBegin) + 1
	return data[:start], data[start:j], data[j:], nil
}

// ReadBlock returns the generated region of the results file.
func ReadBlock(path string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	_, block, _, err := splitBlock(string(data))
	if err != nil {
		return "", fmt.Errorf("%s: %w", path, err)
	}
	return block, nil
}

// WriteBlock replaces the generated region of the results file.
func WriteBlock(path, block string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	before, _, after, err := splitBlock(string(data))
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return os.WriteFile(path, []byte(before+block+after), 0o644)
}

// RunCount re-counts the outputs under dir and prints the table. With write
// it updates results-tokens.md; without, it fails when the file disagrees.
func RunCount(dir string, write bool, w io.Writer) error {
	tok, err := LoadCL100K(filepath.Join(dir, RanksFile))
	if err != nil {
		return err
	}
	res, err := Count(tok, dir)
	if err != nil {
		return err
	}
	table := Render(res)
	fmt.Fprint(w, table)
	results := filepath.Join(dir, ResultsFile)
	if write {
		if err := WriteBlock(results, table); err != nil {
			return err
		}
		fmt.Fprintf(w, "\nwrote %s\n", results)
		return nil
	}
	block, err := ReadBlock(results)
	if err != nil {
		return err
	}
	if block != table {
		return fmt.Errorf("%s does not match the re-count above; run `make bench-tokens-write` if the outputs changed on purpose", results)
	}
	fmt.Fprintf(w, "\n%s matches this re-count.\n", results)
	return nil
}
